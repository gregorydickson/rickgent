// Generates src/build-commit.ts with the current git commit hash.
// Run automatically as part of `pnpm build`.
const { execSync } = require("child_process");
const fs = require("fs");
const path = require("path");

const pinnedCommit = process.env.RICKGENT_BUILD_COMMIT?.trim();
let commit;
if (pinnedCommit) {
  if (!/^[0-9a-f]{40}$/.test(pinnedCommit)) {
    throw new Error("RICKGENT_BUILD_COMMIT must be a lowercase 40-character Git OID");
  }
  commit = pinnedCommit;
} else {
  commit = "dev";
  try {
    commit = execSync("git rev-parse HEAD", { encoding: "utf-8" }).trim();
  } catch {
    // Not a git repo or git unavailable — use "dev"
  }
}

const outPath = path.join(__dirname, "..", "src", "build-commit.ts");
const content = `// AUTO-GENERATED by scripts/generate-build-commit.js — do not edit.\n// This file is regenerated on every \`pnpm build\`.\nexport const BUILD_COMMIT = "${commit}";\n`;

// Only write if content changed (avoid unnecessary rebuilds)
if (!fs.existsSync(outPath) || fs.readFileSync(outPath, "utf-8") !== content) {
  fs.writeFileSync(outPath, content);
  console.log(`build-commit.ts generated: ${commit.slice(0, 12)}`);
}
